import { useMemo, useState } from "react";
import { Alert, EmptyState, Loader, Paper, Stack, Text, Title } from "@mantine/core";
import { IconAlertCircle } from "@tabler/icons-react";
import { PlotControls } from "./PlotControls";
import { PlotlyChart } from "./PlotlyChart";
import { usePlotCatalog } from "../hooks/usePlotCatalog";
import { usePlot } from "../hooks/usePlot";
import type { ChartType, ReportFile, SampleType } from "../types/plots.types";
import "../styles/plot-viewer.css";

interface PlotViewerProps {
  reports: ReportFile[];
}

/** Deriva el tipo de muestra desde el nombre del CSV. */
function detectSampleType(fileName: string): SampleType | null {
  const name = fileName.toUpperCase();
  if (name.includes("SAMPLE-A") || name.includes("A-LOG")) return "A-LOG";
  if (name.includes("SAMPLE-P") || name.includes("P-LOG")) return "P-LOG";
  return null;
}

export function PlotViewer({ reports }: PlotViewerProps) {
  const [sampleType, setSampleType] = useState<SampleType>("A-LOG");
  const [selectedPlotId, setSelectedPlotId] = useState<string | null>(null);
  const [chartType, setChartType] = useState<ChartType>("line");

  // Tipos de muestra realmente presentes en los reportes
  const availableSampleTypes = useMemo(() => {
    const types = new Set<SampleType>();
    reports.forEach((r) => {
      const t = detectSampleType(r.name);
      if (t) types.add(t);
    });
    return types;
  }, [reports]);

  // CSV que corresponde al sampleType actual (el más reciente)
  const csvPath = useMemo(() => {
    const match = reports.find(
      (r) => detectSampleType(r.name) === sampleType,
    );
    return match?.path ?? null;
  }, [reports, sampleType]);

  const { catalog, isLoading: catalogLoading, error: catalogError } =
    usePlotCatalog(sampleType);

  const currentPlotId =
    selectedPlotId && catalog.some((p) => p.id === selectedPlotId)
      ? selectedPlotId
      : (catalog[0]?.id ?? null);

  const { figure, isLoading: plotLoading, error: plotError } = usePlot(
    csvPath,
    currentPlotId,
    chartType,
  );

  if (reports.length === 0) {
    return (
      <Paper className="plot-viewer">
        <Stack className="plot-viewer__content">
          <Stack gap={4}>
            <Title order={3}>Catalog plots</Title>
            <Text c="dimmed" size="sm">
              Interactive plots generated by the Python engine.
            </Text>
          </Stack>
          <EmptyState
            title="No reports available"
            description="Analyze a log file first to generate plots."
          />
        </Stack>
      </Paper>
    );
  }

  return (
    <Paper className="plot-viewer">
      <Stack className="plot-viewer__content">
        <Stack gap={4}>
          <Title order={3}>Catalog plots</Title>
          <Text c="dimmed" size="sm">
            Interactive plots generated by the Python engine.
          </Text>
        </Stack>

        <PlotControls
          sampleType={sampleType}
          onSampleTypeChange={setSampleType}
          availableSampleTypes={availableSampleTypes}
          catalog={catalog}
          selectedPlotId={currentPlotId}
          onPlotChange={setSelectedPlotId}
          chartType={chartType}
          onChartTypeChange={setChartType}
          disabled={catalogLoading}
        />

        {!csvPath && (
          <Alert
            color="yellow"
            icon={<IconAlertCircle size={18} />}
            title="No CSV for this sample"
          >
            No <strong>{sampleType}</strong> CSV was found in the reports
            folder. Process a matching log first.
          </Alert>
        )}

        {catalogError && (
          <Alert
            color="red"
            icon={<IconAlertCircle size={18} />}
            title="Could not load plot catalog"
          >
            {catalogError}
          </Alert>
        )}

        {plotError && (
          <Alert
            color="red"
            icon={<IconAlertCircle size={18} />}
            title="Could not generate the plot"
          >
            {plotError}
          </Alert>
        )}

        {plotLoading && (
          <Stack align="center" py="xl">
            <Loader />
            <Text size="sm">Generating plot…</Text>
          </Stack>
        )}

        {!plotLoading && figure && <PlotlyChart figure={figure} />}
      </Stack>
    </Paper>
  );
}