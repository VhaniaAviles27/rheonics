import { useState } from "react";
import { Paper, Stack, Text, Title } from "@mantine/core";
import { AppLayout } from "./components/layout/AppLayout";
import type { AppView } from "./components/layout/types/app-layout.types";
import { pageInfo } from "./components/layout/constants/page-info.constants";
import { LogUploadPanel } from "./features/log-analysis/components/LogUploadPanel";
import { useLogAnalysis } from "./features/log-analysis/hooks/useLogAnalysis";
import { ReportsPanel } from "./features/reports/components/ReportPanel";
import { OverviewPanel } from "./features/overview/component/OverviewPanel";

function App() {
  const [activeView, setActiveView] = useState<AppView>("overview");
  const { isAnalyzing, result, error, runAnalysis } = useLogAnalysis();
  const currentPage = pageInfo[activeView];

  return (
    <AppLayout
      title={currentPage.title}
      subtitle={currentPage.subtitle}
      activeView={activeView}
      onNavigate={setActiveView}
    >
      <Stack className="app__view">
        <Stack className="app__welcome">

          {activeView === "log-analysis" && (
            <Stack className="app__view">
              <Stack className="app__welcome">
                <Text className="app__eyebrow">LOG PROCESSING</Text>

                <Title className="app__welcome-title" order={3}>
                  Analyze your equipment logs
                </Title>

                <Text className="app__description">
                  Select a raw .LOG file to process its records and inspect data
                  quality.
                </Text>
              </Stack>

              <LogUploadPanel
                onAnalyze={runAnalysis}
                isAnalyzing={isAnalyzing}
              />

              {error && (
                <Paper className="app__error" role="alert">
                  <Title className="app__error-title" order={3}>
                    Analysis failed
                  </Title>

                  <Text className="app__error-description">{error}</Text>
                </Paper>
              )}

              {result && (
                <Text className="app__status-message" role="status">
                  Analysis completed for {result.file_name} (
                  {result.log_type.toUpperCase()}-LOG).
                </Text>
              )}
            </Stack>
          )}

          {activeView === "overview" && (
            <Stack className="app__view">
              <Stack className="app__welcome">
                <Text className="app__eyebrow">WORKSPACE OVERVIEW</Text>
                <Title className="app__welcome-title" order={3}>
                  Welcome to Sensor Log Analyzer
                </Title>
                <Text className="app__description">
                  Analyze equipment logs, inspect data quality, and explore
                  sensor measurements from one workspace.
                </Text>
              </Stack>

              <OverviewPanel />
            </Stack>
          )}

          {activeView === "reports" && (
            <Stack className="app__view">
              <Stack className="app__welcome">
                <Text className="app__eyebrow">ANALYSIS OUTPUTS</Text>
                <Title className="app__welcome-title" order={3}>
                  Reports
                </Title>
                <Text className="app__description">
                  Browse the CSV files generated by the analysis pipeline.
                </Text>
              </Stack>

              <ReportsPanel />
            </Stack>
          )}

          <Text className="app__description">
            Analyze equipment logs, inspect data quality, and explore sensor
            measurements from one workspace.
          </Text>
        </Stack>
      </Stack>
    </AppLayout>
  );
}

export default App;
